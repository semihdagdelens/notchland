import AppKit

/// Panoya kopyalanan metin, bağlantı, görsel ve dosyaların geçmişi.
/// Şifre yöneticilerinin gizli/geçici olarak işaretlediği kopyalar kaydedilmez (nspasteboard.org).
@Observable
final class ClipboardStore {
    struct Item: Identifiable, Codable, Equatable {
        enum Kind: String, Codable {
            case text, link, image, files
        }

        let id: UUID
        let kind: Kind
        var text: String?
        var filePaths: [String]?
        /// Görselin kaydedildiği dosya adı (depolama klasöründe).
        var imageFile: String?
        var date: Date
        var sourceBundleID: String?
        /// Görsellerin piksel boyutu (eski kayıtlarda yok).
        var pixelWidth: Int?
        var pixelHeight: Int?
        /// macOS ekran görüntüsünden geldi (dosyası `filePaths` içinde).
        var isScreenshot: Bool?

        /// Yinelenenleri bulmak için içerik anahtarı.
        var contentKey: String {
            switch kind {
            case .text, .link: "t:" + (text ?? "")
            case .files: "f:" + (filePaths ?? []).joined(separator: "\n")
            case .image: "i:" + id.uuidString
            }
        }
    }

    static var maxItems: Int { AppSettings.shared.clipboardMaxItems }
    private static let maxImageBytes = 15 * 1024 * 1024
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private(set) var items: [Item] = []

    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var imageCache: [UUID: NSImage] = [:]

    @ObservationIgnored private let directory: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = base.appendingPathComponent("UstBar/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()
    private var historyURL: URL { directory.appendingPathComponent("history.json") }

    func start() {
        load()
        // changeCount okumak ucuz; tolerans macOS'in uyanmaları birleştirmesine izin verir.
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        startScreenshotWatcher()
    }

    // MARK: - Ekran görüntüleri

    @ObservationIgnored private var screenshotQuery: NSMetadataQuery?
    @ObservationIgnored private var screenshotObserver: Any?

    /// Ekran görüntülerinin kaydedildiği klasör (Ekran Görüntüsü > Seçenekler > Kaydet; varsayılan Masaüstü).
    private static var screenshotFolder: URL {
        let custom = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location")
        if let custom, !custom.isEmpty {
            return URL(fileURLWithPath: (custom as NSString).expandingTildeInPath, isDirectory: true)
        }
        return FileManager.default.urls(for: .desktopDirectory, in: .userDomainMask)[0]
    }

    /// Masaüstüne (veya seçilen konuma) kaydedilen yeni ekran görüntülerini Spotlight ile yakalar.
    /// Olay tabanlıdır; sürekli dosya taraması yapmaz.
    ///
    /// Masaüstü/Belgeler/İndirilenler macOS tarafından korunur: izin yokken Spotlight bu klasörlerdeki
    /// sonuçları uygulamaya sessizce göstermez. Bu yüzden klasöre bir kez dokunup izin penceresini
    /// tetikliyor, ardından sorguyu (izin verildiyse artık sonuç döndürecek şekilde) yeniden kuruyoruz.
    private func startScreenshotWatcher() {
        guard AppSettings.shared.clipboardScreenshots else { return }
        let folder = Self.screenshotFolder
        DispatchQueue.global(qos: .utility).async { [weak self] in
            // İzin penceresi cevaplanana kadar bekleyebilir; ana kuyruğu bloklamasın.
            _ = try? FileManager.default.contentsOfDirectory(atPath: folder.path)
            DispatchQueue.main.async { self?.restartScreenshotQuery() }
        }
    }

    private func restartScreenshotQuery() {
        screenshotQuery?.stop()
        if let screenshotObserver { NotificationCenter.default.removeObserver(screenshotObserver) }

        let query = NSMetadataQuery()
        query.predicate = NSPredicate(
            format: "kMDItemIsScreenCapture == 1 AND kMDItemFSCreationDate >= %@", Date() as NSDate
        )
        query.searchScopes = [NSMetadataQueryUserHomeScope]
        screenshotObserver = NotificationCenter.default.addObserver(
            forName: .NSMetadataQueryDidUpdate, object: query, queue: .main
        ) { [weak self] note in
            let added = note.userInfo?[NSMetadataQueryUpdateAddedItemsKey] as? [NSMetadataItem] ?? []
            for item in added {
                guard let path = item.value(forAttribute: NSMetadataItemPathKey) as? String else { continue }
                self?.addScreenshot(at: URL(fileURLWithPath: path))
            }
        }
        query.start()
        screenshotQuery = query
    }

    private func addScreenshot(at url: URL) {
        guard AppSettings.shared.clipboardEnabled, AppSettings.shared.clipboardScreenshots else { return }
        guard !items.contains(where: { $0.isScreenshot == true && $0.filePaths?.first == url.path }) else { return }
        guard let data = try? Data(contentsOf: url), data.count <= Self.maxImageBytes,
              let rep = NSBitmapImageRep(data: data) else { return }
        let id = UUID()
        let fileName = id.uuidString + "." + (url.pathExtension.isEmpty ? "png" : url.pathExtension.lowercased())
        guard (try? data.write(to: directory.appendingPathComponent(fileName))) != nil else { return }
        insert(Item(
            id: id, kind: .image, filePaths: [url.path], imageFile: fileName, date: Date(),
            sourceBundleID: "com.apple.screenshot.launcher",
            pixelWidth: rep.pixelsWide, pixelHeight: rep.pixelsHigh, isScreenshot: true
        ))
    }

    // MARK: - Okuma

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard AppSettings.shared.clipboardEnabled else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard var item = Self.makeItem(from: pasteboard, directory: directory) else { return }
        item.sourceBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        insert(item)
    }

    private static func makeItem(from pasteboard: NSPasteboard, directory: URL) -> Item? {
        let now = Date()
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return Item(id: UUID(), kind: .files, filePaths: urls.map(\.path), date: now)
        }
        if pasteboard.availableType(from: [.png, .tiff]) != nil,
           let image = NSImage(pasteboard: pasteboard),
           let tiff = image.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]),
           png.count <= maxImageBytes {
            let id = UUID()
            let fileName = id.uuidString + ".png"
            guard (try? png.write(to: directory.appendingPathComponent(fileName))) != nil else { return nil }
            return Item(id: id, kind: .image, imageFile: fileName, date: now,
                        pixelWidth: rep.pixelsWide, pixelHeight: rep.pixelsHigh)
        }
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(where: \.isWhitespace)
                && URL(string: trimmed).map { ["http", "https"].contains($0.scheme?.lowercased() ?? "") } == true
            return Item(id: UUID(), kind: isLink ? .link : .text, text: string, date: now)
        }
        return nil
    }

    private func insert(_ item: Item) {
        if let existing = items.firstIndex(where: { $0.contentKey == item.contentKey }) {
            var moved = items.remove(at: existing)
            moved.date = item.date
            moved.sourceBundleID = item.sourceBundleID
            items.insert(moved, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        while items.count > Self.maxItems {
            deleteFiles(of: items.removeLast())
        }
        save()
    }

    // MARK: - Eylemler

    /// Öğeyi panoya geri koyar. `paste` true ise öndeki uygulamaya ⌘V gönderir.
    func copy(_ item: Item, paste: Bool) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .files:
            pasteboard.writeObjects((item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        }
        // Kendi yazdığımız değişikliği geçmişe tekrar ekleme; sadece en üste taşı.
        lastChangeCount = pasteboard.changeCount
        if let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
        if paste {
            // Tıklamanın bırakılması işlensin, sonra yapıştır.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { Self.sendPasteShortcut() }
        }
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        deleteFiles(of: item)
        save()
    }

    func removeAll() {
        items.forEach(deleteFiles)
        items.removeAll()
        save()
    }

    func image(for item: Item) -> NSImage? {
        if let cached = imageCache[item.id] { return cached }
        guard let file = item.imageFile,
              let image = NSImage(contentsOf: directory.appendingPathComponent(file)) else { return nil }
        imageCache[item.id] = image
        return image
    }

    private func deleteFiles(of item: Item) {
        imageCache[item.id] = nil
        if let file = item.imageFile {
            try? FileManager.default.removeItem(at: directory.appendingPathComponent(file))
        }
    }

    /// Erişilebilirlik izni gerektirir (ses tuşları için zaten veriliyor).
    private static func sendPasteShortcut() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    // MARK: - Kalıcılık

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let saved = try? JSONDecoder().decode([Item].self, from: data) else { return }
        items = saved
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}
